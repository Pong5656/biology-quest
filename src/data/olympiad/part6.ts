/** สลับตัวเลือกแบบคงที่จากข้อความคำถาม → เฉลยกระจาย ไม่ตกที่ตัวเลือกแรกเสมอ */
const hashText = (s: string): number => {
  let h = 2166136261;
  for (let i = 0; i < s.length; i++) {
    h ^= s.charCodeAt(i);
    h = Math.imul(h, 16777619);
  }
  return h >>> 0;
};
const f = (
  question: string,
  a: string,
  b: string,
  c: string,
  d: string,
  answer: 0 | 1 | 2 | 3,
  explanation: string,
  hint: string,
): ExamQuestion => {
  const choices = [a, b, c, d];
  const correct = choices[answer];
  let seed = hashText(question);
  const rand = () => {
    seed = (seed + 0x6d2b79f5) | 0;
    let t = seed;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
  for (let i = choices.length - 1; i > 0; i--) {
    const j = Math.floor(rand() * (i + 1));
    [choices[i], choices[j]] = [choices[j], choices[i]];
  }
  return q(question, choices, choices.indexOf(correct), explanation, hint);
};

